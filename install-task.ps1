# 注册 / 卸载 Windows 计划任务：每天定时跑邮件日报
# 用法（不需要管理员；但如果在 DSH 沙箱里跑，写任务存储会被拦，需要放宽权限）：
#   .\install-task.ps1                 # 默认每天 20:00
#   .\install-task.ps1 -Time 07:30
#   .\install-task.ps1 -Visible        # 不用隐藏窗口的 VBS 包装（调试用，会闪一下黑窗）
#   .\install-task.ps1 -Uninstall
#   .\install-task.ps1 -Time 20:00 -WakeToRun   # 睡眠时也到点唤醒（见 README「定时与开机的关系」）
#
# 会注册**两个**任务：
#   MailDigest-Daily    每天 20:00 发当天那份日报
#   MailDigest-Catchup  登录后 2 分钟检查一次，**只在最近一个 20:00 确实错过时**才补发
#
# 为什么拆成两个（2026-10-27 修）：以前登录触发器直接挂在日报任务上，且补跑无条件执行 ——
# 19:22 登录立刻发一封（13 封那批），20:00 定时器再发一封（新增 10 封），同一天两封。
# 现在补跑单独成任务、带 `--catch-up`，程序里先判断「最近一个 20:00 之后是否已经成功发过」，
# 发过就静默退出（见 lib\window.mjs 的 shouldCatchUp 与它的测试）。
[CmdletBinding()]
param(
  [string]$TaskName = "MailDigest-Daily",
  [string]$Time = "20:00",
  [switch]$Visible,
  [switch]$WakeToRun,
  [switch]$Uninstall
)

$ErrorActionPreference = "Stop"
$root = $PSScriptRoot
$CatchUpTaskName = "$TaskName-Catchup"

function Run-SchTasks([string]$Arguments) {
  $out = & cmd.exe /c "schtasks $Arguments" 2>&1
  return @{ Code = $LASTEXITCODE; Output = ($out | Out-String).Trim() }
}

if ($Uninstall) {
  foreach ($n in @($TaskName, $CatchUpTaskName)) {
    $r = Run-SchTasks "/Delete /TN `"$n`" /F"
    if ($r.Code -eq 0) { Write-Host "[OK] 已删除计划任务 $n" -ForegroundColor Green }
    else { Write-Host "[--] 删除失败或任务不存在：$n" -ForegroundColor Yellow }
  }
  return
}

# ---------- 1) 确定 node.exe（优先项目自带 runtime\node.exe，避免依赖 DSH）----------
$node = Join-Path $root "runtime\node.exe"
if (-not (Test-Path $node)) {
  $found = Get-Command node.exe -ErrorAction SilentlyContinue
  if ($found) { $node = $found.Source }
}
if (-not (Test-Path $node)) {
  throw "找不到 node.exe，请把 node.exe 放到 $root\runtime\"
}
if (-not (Test-Path (Join-Path $root "main-outlook.mjs"))) { throw "找不到 $root\main-outlook.mjs" }

New-Item -ItemType Directory -Force -Path (Join-Path $root "logs") | Out-Null

# ---------- 2) 构造要执行的命令（默认用 VBS 包装，避免弹黑窗）----------
# 注意：入口是 main-outlook.mjs（Outlook COM 通道）。main.mjs 是旧的 Graph 通道，
# 需要学校管理员同意才能用，保留作备用，不要挂到计划任务上。
$logFile = Join-Path $root "logs\task.log"
# 计划任务用 cmd >> 追加日志；运行期间文件句柄被 cmd 占着，只能让 node 启动前
# 由一个独立进程轮转一次，否则 task.log 会无限增长。
$rotator = Join-Path $root "rotate-task-log.cmd"
$rotBody = @"
@echo off
for %%F in ("$logFile") do if %%~zF GTR 5242880 move /y "%%~F" "%%~F.1" >nul 2>&1
"@
[System.IO.File]::WriteAllText($rotator, $rotBody, [System.Text.Encoding]::ASCII)

function Build-Inner([string]$extraArgs) {
  "cd /d `"$root`" && `"$rotator`" && `"$node`" main-outlook.mjs$extraArgs >> `"$logFile`" 2>&1"
}
$inner = Build-Inner ""
$innerCatch = Build-Inner " --catch-up"

function New-Vbs([string]$path, [string]$cmdLine) {
  $line = $cmdLine -replace '"', '""'
  $body = @"
' Generated by install-task.ps1 - run mail digest with a hidden window
' bWaitOnReturn=True + WScript.Quit(rc): pass node's exit code back to Task Scheduler
' so "Last Run Result" is meaningful (0 ok / 2 needs re-login / 3 other failure).
Set sh = CreateObject("WScript.Shell")
rc = sh.Run("cmd /c $line", 0, True)
WScript.Quit rc
"@
  # VBS 用 ASCII 写，避免编码问题（内容本身没有中文）
  [System.IO.File]::WriteAllText($path, $body, [System.Text.Encoding]::ASCII)
}

if ($Visible) {
  $exec = "cmd.exe"
  $execArgs = "/c $inner"
  $catchExec = "cmd.exe"
  $catchArgs = "/c $innerCatch"
} else {
  $vbs = Join-Path $root "run-hidden.vbs"
  $vbsCatch = Join-Path $root "run-hidden-catchup.vbs"
  New-Vbs $vbs $inner
  New-Vbs $vbsCatch $innerCatch
  $exec = "wscript.exe"
  $execArgs = "`"$vbs`""
  $catchExec = "wscript.exe"
  $catchArgs = "`"$vbsCatch`""
}

# ---------- 3) 生成任务 XML 并注册 ----------
$userId = "$env:USERDOMAIN\$env:USERNAME"
$startBoundary = (Get-Date -Format "yyyy-MM-dd") + "T" + $Time + ":00"

function New-TaskXml([string]$name, [string]$desc, [string]$triggers, [string]$cmd, [string]$cmdArgs) {
  return @"
<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>$desc</Description>
    <URI>\$name</URI>
  </RegistrationInfo>
  <Triggers>
$triggers
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>$userId</UserId>
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <IdleSettings>
      <StopOnIdleEnd>false</StopOnIdleEnd>
      <RestartOnIdle>false</RestartOnIdle>
    </IdleSettings>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <RunOnlyIfIdle>false</RunOnlyIfIdle>
    <WakeToRun>$($WakeToRun.IsPresent.ToString().ToLower())</WakeToRun>
    <ExecutionTimeLimit>PT1H</ExecutionTimeLimit>
    <RestartOnFailure>
      <Interval>PT10M</Interval>
      <Count>2</Count>
    </RestartOnFailure>
    <Priority>7</Priority>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>$cmd</Command>
      <Arguments>$cmdArgs</Arguments>
    </Exec>
  </Actions>
</Task>
"@
}

function Register-Task([string]$name, [string]$xml) {
  $p = Join-Path $env:TEMP "$name.xml"
  # schtasks 读 XML 时按声明解析，用 UTF-16 写最稳
  [System.IO.File]::WriteAllText($p, $xml, (New-Object System.Text.UnicodeEncoding($false, $true)))
  return Run-SchTasks "/Create /XML `"$p`" /TN `"$name`" /F"
}

# 3.1 每天 20:00 的那份（只有一个日历触发器，登录补跑已经分出去了）
$dailyTriggers = @"
    <CalendarTrigger>
      <StartBoundary>$startBoundary</StartBoundary>
      <Enabled>true</Enabled>
      <ScheduleByDay>
        <DaysInterval>1</DaysInterval>
      </ScheduleByDay>
    </CalendarTrigger>
"@
$xmlDaily = New-TaskXml $TaskName "每天生成 Outlook 邮件日报并发回自己邮箱（mail-digest）" $dailyTriggers $exec $execArgs
$reg = Register-Task $TaskName $xmlDaily
$method = "XML"
if ($reg.Code -ne 0) {
  Write-Host "[!] 日报任务 XML 注册失败，回退到命令行方式：$($reg.Output)" -ForegroundColor Yellow
  $tr = "$exec $execArgs"
  $reg = Run-SchTasks "/Create /TN `"$TaskName`" /TR `"$tr`" /SC DAILY /ST $Time /F"
  $method = "命令行"
}
if ($reg.Code -ne 0) {
  Write-Host "[X] 日报任务注册失败：$($reg.Output)" -ForegroundColor Red
  exit 1
}

# 3.2 登录补跑（带 --catch-up，程序自己判断该不该补）
# 为什么不能只靠 StartWhenAvailable 补跑：它要在"任务计划程序服务启动那一刻"判定错过，
# 那时通常还没登录，而本任务是 InteractiveToken（必须登录后才跑得起来），补跑就落空了
# —— 2026-09-23 实测：20:00 关机，开机后一直没补。
$catchTriggers = @"
    <LogonTrigger>
      <Enabled>true</Enabled>
      <UserId>$userId</UserId>
      <Delay>PT2M</Delay>
    </LogonTrigger>
"@
$xmlCatch = New-TaskXml $CatchUpTaskName "登录后补跑错过的邮件日报（只在最近一个 20:00 没发过时才补）" $catchTriggers $catchExec $catchArgs
$regCatch = Register-Task $CatchUpTaskName $xmlCatch
if ($regCatch.Code -ne 0) {
  Write-Host "[X] 补跑任务注册失败：$($regCatch.Output)" -ForegroundColor Red
  exit 1
}

# ---------- 4) 回读确认 ----------
Write-Host "[OK] 已注册两个计划任务（日报任务用 $method 方式）" -ForegroundColor Green
foreach ($name in @($TaskName, $CatchUpTaskName)) {
  $q = Run-SchTasks "/Query /TN `"$name`" /FO LIST /V"
  Write-Host ""
  Write-Host "  ---- $name ----"
  foreach ($k in "TaskName", "Next Run Time", "Status", "Task To Run", "Schedule Type", "Start Time", "Run As User") {
    $line = ($q.Output -split "`r?`n" | Where-Object { $_ -match "^\s*$([regex]::Escape($k))\s*:" })
    if ($line) { Write-Host ("     " + $line.Trim()) }
  }
}
Write-Host ""
Write-Host "     日志：$logFile"
Write-Host ""
Write-Host "手动试跑一次： schtasks /Run /TN `"$TaskName`""
Write-Host "查看结果：     Get-Content `"$logFile`" -Tail 40 -Encoding UTF8"
